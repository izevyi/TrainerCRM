#!/usr/bin/env bash
set -euo pipefail

# Persistent, isolated browser demo. This script never reads project dotenv files.

script_dir="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
root_dir="$(CDPATH= cd -- "$script_dir/../.." && pwd)"
frontend_dir="$root_dir/frontend-app"
migrations_dir="$root_dir/database-development/migrations"
data_home="${XDG_DATA_HOME:-$HOME/.local/share}"
state_dir="$data_home/trainercrm-pilot"
pgdata="$state_dir/pgdata"
socket_dir="$state_dir/socket"
config_file="$state_dir/config"
credentials_file="$state_dir/credentials.txt"
initialized_file="$state_dir/initialized"
postgres_log="$state_dir/postgres.log"
app_log="$state_dir/application.log"
app_pid_file="$state_dir/application.pid"
app_start_file="$state_dir/application.starttime"
instance_marker="trainercrm-persistent-pilot"

fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<EOF
Usage: $0 start|stop|status|backup|preserve-old|reset|credential-self-test

  start         initialize once if needed, then start PostgreSQL and Next.js
  stop          stop this demo without deleting data
  status        report PostgreSQL, application, URL, and credential location
  backup        write a timestamped custom-format dump under the state directory
  preserve-old  archive an explicitly named old demo database (see command help)
  reset         delete this demo only after an exact interactive confirmation
  credential-self-test  validate UUID/password-hash generation without PostgreSQL

Backup: $0 backup
Optional old-demo archive (never imported):
  $0 preserve-old trainercrm_demo_<hex-suffix>

Recovery after interruption or WSL shutdown:
  1. Run '$0 status', then '$0 stop' to clear only verified processes.
  2. Run '$0 start'; PostgreSQL safely reuses the persistent cluster.
  3. If first initialization was interrupted, stop, then use the separately
     confirmed '$0 reset' and start again.
  4. A Next.js lock is never removed automatically. Verify that no other demo
     owns frontend-app/.next/dev/lock before removing a genuinely stale lock.
EOF
}

find_postgres_bindir() {
  local candidate executable
  if command -v pg_config >/dev/null 2>&1; then
    candidate="$(pg_config --bindir 2>/dev/null || true)"
    if [ -n "$candidate" ]; then
      for executable in initdb pg_ctl postgres psql pg_dump pg_restore; do
        [ -x "$candidate/$executable" ] || candidate=""
      done
      [ -n "$candidate" ] && { printf '%s\n' "$candidate"; return; }
    fi
  fi
  for candidate in /usr/lib/postgresql/*/bin /usr/local/pgsql/bin; do
    [ -d "$candidate" ] || continue
    for executable in initdb pg_ctl postgres psql pg_dump pg_restore; do
      [ -x "$candidate/$executable" ] || candidate=""
    done
    [ -n "$candidate" ] && { printf '%s\n' "$candidate"; return; }
  done
  return 1
}

require_native_storage() {
  local resolved_state
  case "$state_dir/" in
    /tmp/*|/run/*|/mnt/*) fail "Persistent state must be on the native WSL filesystem, not $state_dir" ;;
  esac
  [ ! -L "$state_dir" ] || fail "Refusing symlinked state directory: $state_dir"
  resolved_state="$(realpath -m "$state_dir")"
  case "$resolved_state/" in
    /tmp/*|/run/*|/mnt/*) fail "Persistent state resolves outside the native WSL filesystem: $resolved_state" ;;
  esac
}

load_config() {
  [ -r "$config_file" ] || fail "Persistent configuration is missing: $config_file"
  [ "$(stat -c %u "$config_file")" = "$(id -u)" ] || fail "Configuration is not owned by the current user"
  [ "$(stat -c %a "$config_file")" = 600 ] || fail "Configuration permissions must be 600"
  # Make a truncated/old config fail validation below, rather than at an
  # arbitrary later expansion under set -u.
  pg_port="" app_port="" database_name="" cluster_admin="" operator_role="" app_role="" app_password=""
  # Generated by this script, mode 600, fixed key/value syntax only.
  . "$config_file"
  [[ "$pg_port" =~ ^[0-9]+$ ]] && [ "$pg_port" -ge 1 ] && [ "$pg_port" -le 65535 ] &&
    [[ "$app_port" =~ ^[0-9]+$ ]] && [ "$app_port" -ge 1 ] && [ "$app_port" -le 65535 ] || fail "Invalid saved ports"
  [[ "$database_name" =~ ^trainercrm_persistent_[a-f0-9]+$ ]] || fail "Invalid saved database name"
  [ "$cluster_admin" = trainercrm_persistent_cluster_admin ] || fail "Invalid saved cluster administrator role"
  [ "$operator_role" = trainercrm_persistent_operator ] || fail "Invalid saved operator role"
  [ "$app_role" = trainercrm_app ] || fail "Invalid saved application role"
  [[ "$app_password" =~ ^[a-f0-9]{64}$ ]] || fail "Invalid or missing saved application password"
}

postgres_running() {
  [ -s "$pgdata/PG_VERSION" ] && "$pg_ctl" -D "$pgdata" status >/dev/null 2>&1
}

read_app_identity() {
  app_pid="" app_start=""
  [ -r "$app_pid_file" ] && [ -r "$app_start_file" ] || return 1
  app_pid="$(<"$app_pid_file")"
  app_start="$(<"$app_start_file")"
  [[ "$app_pid" =~ ^[1-9][0-9]*$ ]] || return 1
  [ "$(awk '{print $22}' "/proc/$app_pid/stat" 2>/dev/null || true)" = "$app_start" ] || return 1
  [ "$(awk '{print $5}' "/proc/$app_pid/stat" 2>/dev/null || true)" = "$app_pid" ] || return 1
  tr '\0' '\n' <"/proc/$app_pid/environ" 2>/dev/null | grep -Fqx "TRAINERCRM_PILOT_INSTANCE=$instance_marker"
}

load_app_group_id() {
  [ -r "$app_pid_file" ] || return 1
  app_pid="$(<"$app_pid_file")"
  [[ "$app_pid" =~ ^[1-9][0-9]*$ ]]
}

random_port() {
  node <<'NODE'
const server = require("node:net").createServer();
server.listen(0, "127.0.0.1", () => {
  process.stdout.write(String(server.address().port)); server.close();
});
NODE
}

port_available() {
  PORT_TO_CHECK="$1" node <<'NODE'
const server = require("node:net").createServer();
server.once("error", () => process.exit(1));
server.listen(Number(process.env.PORT_TO_CHECK), "127.0.0.1", () => server.close(() => process.exit(0)));
NODE
}

save_config() {
  local temporary_config="$config_file.new.$$"
  {
    printf 'pg_port=%q\napp_port=%q\ndatabase_name=%q\ncluster_admin=%q\noperator_role=%q\napp_role=%q\napp_password=%q\n' \
      "$pg_port" "$app_port" "$database_name" "$cluster_admin" "$operator_role" "$app_role" "$app_password"
  } >"$temporary_config"
  chmod 600 "$temporary_config"
  mv -f -- "$temporary_config" "$config_file"
}

choose_available_ports() {
  local changed=no
  if ! postgres_running && ! port_available "$pg_port"; then
    pg_port="$(random_port)"; changed=yes
  fi
  if ! read_app_identity && ! port_available "$app_port"; then
    app_port="$(random_port)"; changed=yes
  fi
  while [ "$pg_port" = "$app_port" ]; do app_port="$(random_port)"; changed=yes; done
  [ "$changed" = no ] || save_config
}

app_group_members() {
  local stat pid pgrp
  [[ "${app_pid:-}" =~ ^[1-9][0-9]*$ ]] || load_app_group_id || return 1
  for stat in /proc/[1-9]*/stat; do
    pid="${stat#/proc/}"; pid="${pid%/stat}"
    pgrp="$(awk '{print $5}' "$stat" 2>/dev/null || true)"
    [ "$pgrp" = "$app_pid" ] || continue
    tr '\0' '\n' <"/proc/$pid/environ" 2>/dev/null | grep -Fqx "TRAINERCRM_PILOT_INSTANCE=$instance_marker" || continue
    printf '%s\n' "$pid"
  done
}

stop_app_group() {
  local members pid
  members="$(app_group_members || true)"
  [ -n "$members" ] || return 0
  while IFS= read -r pid; do kill -TERM "$pid" 2>/dev/null || true; done <<<"$members"
  for _ in $(seq 1 100); do
    [ -z "$(app_group_members || true)" ] && return 0
    sleep 0.1
  done
  return 1
}

generate_synthetic_credentials() {
  local trainer_one_password_input="$1" trainer_two_password_input="$2"
  local generated_output
  if ! generated_output="$(
    TRAINER_ONE_PASSWORD="$trainer_one_password_input" \
    TRAINER_TWO_PASSWORD="$trainer_two_password_input" node <<'NODE'
const { randomBytes, randomUUID, scrypt } = require("node:crypto");
const { promisify } = require("node:util");

const derive = promisify(scrypt);
const parameters = { N: 16384, r: 8, p: 1, maxmem: 32 * 1024 * 1024 };

async function hash(password) {
  if (typeof password !== "string" || Buffer.byteLength(password, "utf8") === 0 ||
      Buffer.byteLength(password, "utf8") > 1024) {
    throw Object.assign(new Error("invalid synthetic password"), { code: "PASSWORD_INPUT_INVALID" });
  }
  const salt = randomBytes(16);
  const key = await derive(password, salt, 32, parameters);
  const encoded = `$scrypt$v=1$N=16384,r=8,p=1$${salt.toString("base64url")}$${key.toString("base64url")}`;
  const match = /^\$scrypt\$v=1\$N=16384,r=8,p=1\$([A-Za-z0-9_-]{22})\$([A-Za-z0-9_-]{43})$/.exec(encoded);
  if (!match || !key.equals(await derive(password, Buffer.from(match[1], "base64url"), 32, parameters)) ||
      key.equals(await derive(`${password}-wrong`, Buffer.from(match[1], "base64url"), 32, parameters))) {
    throw Object.assign(new Error("scrypt verification mismatch"), { code: "SCRYPT_VERIFY_FAILED" });
  }
  return encoded;
}

(async () => {
  const ids = Array.from({ length: 6 }, () => randomUUID());
  const hashes = await Promise.all([
    hash(process.env.TRAINER_ONE_PASSWORD),
    hash(process.env.TRAINER_TWO_PASSWORD),
  ]);
  process.stdout.write([...ids, ...hashes].join("\n") + "\n");
})().catch(error => {
  const code = typeof error?.code === "string" ? error.code : "UNKNOWN";
  process.stderr.write(`Credential generator failed (${code}).\n`);
  process.exitCode = 1;
});
NODE
  )"; then
    fail "Synthetic credential generation failed; Node.js reported a non-secret diagnostic above."
  fi

  mapfile -t generated_credentials <<<"$generated_output"
  [ "${#generated_credentials[@]}" -eq 8 ] ||
    fail "Synthetic credential generation returned ${#generated_credentials[@]} records; expected 8."
  demo_ids=("${generated_credentials[@]:0:6}")
  password_hashes=("${generated_credentials[@]:6:2}")
  local value
  for value in "${demo_ids[@]}"; do
    [[ "$value" =~ ^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$ ]] ||
      fail "Synthetic credential generation returned an invalid UUID record."
  done
  for value in "${password_hashes[@]}"; do
    [[ "$value" =~ ^\$scrypt\$v=1\$N=16384,r=8,p=1\$[A-Za-z0-9_-]{22}\$[A-Za-z0-9_-]{43}$ ]] ||
      fail "Synthetic credential generation returned an invalid password-hash record."
  done
  unset generated_output generated_credentials
}

credential_self_test() {
  ( generate_synthetic_credentials 'synthetic-preflight-one' 'synthetic-preflight-two' )
  printf 'Credential generation self-test passed.\n'
}

initialize() {
  [ ! -e "$pgdata/PG_VERSION" ] || fail "Partial initialization found. Run '$0 reset' only if this demo can be discarded."
  local suffix trainer_one_password trainer_two_password
  suffix="$(openssl rand -hex 8)"
  pg_port="$(random_port)"; app_port="$(random_port)"
  while [ "$pg_port" = "$app_port" ]; do app_port="$(random_port)"; done
  database_name="trainercrm_persistent_$suffix"
  cluster_admin="trainercrm_persistent_cluster_admin"
  operator_role="trainercrm_persistent_operator"
  app_role="trainercrm_app"
  app_password="$(openssl rand -hex 32)"
  trainer_one_password="$(openssl rand -base64 30 | tr -d '\n')"
  trainer_two_password="$(openssl rand -base64 30 | tr -d '\n')"

  # Complete and validate all fallible credential work before creating PGDATA.
  generate_synthetic_credentials "$trainer_one_password" "$trainer_two_password"

  save_config

  mkdir "$pgdata"
  chmod 700 "$pgdata"
  "$initdb" -D "$pgdata" --username="$cluster_admin" --auth-local=trust --auth-host=reject --no-locale --encoding=UTF8 >/dev/null
  {
    printf 'local all all trust\n'
    printf 'host %s %s 127.0.0.1/32 scram-sha-256\n' "$database_name" "$app_role"
    printf 'host all all 127.0.0.1/32 reject\n'
    printf 'host all all ::1/128 reject\n'
  } >"$pgdata/pg_hba.conf"
  initialization_in_progress=yes
  start_postgres_raw

  "$psql" -X -h "$socket_dir" -p "$pg_port" -U "$cluster_admin" -d postgres -v ON_ERROR_STOP=1 <<'SQL' >/dev/null
BEGIN;
CREATE ROLE trainercrm_persistent_operator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE trainercrm_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE trainercrm_clients_function_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
GRANT trainercrm_clients_function_owner TO trainercrm_persistent_operator;
COMMIT;
SQL
  {
    printf "\\set app_password '%s'\n" "$app_password"
    cat <<'SQL'
ALTER ROLE trainercrm_app PASSWORD :'app_password';
SELECT format('CREATE DATABASE %I OWNER trainercrm_persistent_operator', :'database_name') \gexec
SELECT format('REVOKE CONNECT ON DATABASE %I FROM PUBLIC', :'database_name') \gexec
SELECT format('GRANT CONNECT ON DATABASE %I TO trainercrm_app', :'database_name') \gexec
SQL
  } | "$psql" -X -h "$socket_dir" -p "$pg_port" -U "$cluster_admin" -d postgres -v ON_ERROR_STOP=1 -v database_name="$database_name" >/dev/null

  local migration
  for migration in "$migrations_dir"/{001_extensions,002_schema,003_booking_functions,004_auth_foundation,005_auth_invitation_commands,006_email_subject_compatibility,007_auth_invitation_acceptance,008_auth_preauth_nonce_consumption,009_trainer_login_foundation,010_trainer_login_runtime,011_trainer_clients_runtime}.sql; do
    "$psql" -X -h "$socket_dir" -p "$pg_port" -U "$operator_role" -d "$database_name" -v ON_ERROR_STOP=1 -f "$migration" >/dev/null
  done

  "$psql" -X -h "$socket_dir" -p "$pg_port" -U "$operator_role" -d "$database_name" -v ON_ERROR_STOP=1 \
    -v t1="${demo_ids[0]}" -v u1="${demo_ids[1]}" -v i1="${demo_ids[2]}" -v t2="${demo_ids[3]}" -v u2="${demo_ids[4]}" -v i2="${demo_ids[5]}" \
    -v h1="${password_hashes[0]}" -v h2="${password_hashes[1]}" <<'SQL' >/dev/null
BEGIN;
INSERT INTO booking.tenants(id,public_slug) VALUES (:'t1','persistent-demo-trainer-one'),(:'t2','persistent-demo-trainer-two');
INSERT INTO booking.auth_subjects(id,role,synthetic_phone_ref) VALUES (:'u1','trainer','synthetic:persistent_demo_one'),(:'u2','trainer','synthetic:persistent_demo_two');
INSERT INTO booking.trainer_memberships(tenant_id,trainer_id) VALUES (:'t1',:'u1'),(:'t2',:'u2');
INSERT INTO authn.email_identities(id,subject_id,normalization_version,canonical_email,display_email,verified_at) VALUES
(:'i1',:'u1',1,'trainer.one@example.invalid','trainer.one@example.invalid',transaction_timestamp()),
(:'i2',:'u2',1,'trainer.two@example.invalid','trainer.two@example.invalid',transaction_timestamp());
INSERT INTO authn.trainer_password_credentials(trainer_subject_id,email_identity_id,password_hash,password_changed_at) VALUES
(:'u1',:'i1',:'h1',transaction_timestamp()),(:'u2',:'i2',:'h2',transaction_timestamp());
COMMIT;
SQL
  # Prove that the same TCP role/password pair the application will use is
  # accepted before writing the success marker.
  PGPASSWORD="$app_password" "$psql" -X -At -h 127.0.0.1 -p "$pg_port" -U "$app_role" \
    -d "$database_name" -v ON_ERROR_STOP=1 -c 'SELECT 1' >/dev/null
  {
    printf 'Browser URL: http://127.0.0.1:%s\n\n' "$app_port"
    printf 'Trainer one\nEmail: trainer.one@example.invalid\nPassword: %s\nTenant: persistent-demo-trainer-one\n\n' "$trainer_one_password"
    printf 'Trainer two\nEmail: trainer.two@example.invalid\nPassword: %s\nTenant: persistent-demo-trainer-two\n' "$trainer_two_password"
  } >"$credentials_file"
  chmod 600 "$config_file" "$credentials_file"
  local initialized_file_new="$initialized_file.new.$$"
  printf 'migrations=001-011\ninitialized_at=%s\n' "$(date -u +%FT%TZ)" >"$initialized_file_new"
  chmod 600 "$initialized_file_new"
  mv -f -- "$initialized_file_new" "$initialized_file"
  initialization_in_progress=no
  initialization_server_started=no
}

build_database_url() {
  # All fields are constrained to URL-safe formats by initialize/load_config.
  [ -n "${app_password:-}" ] || fail "Application password is unavailable; persistent configuration is incomplete."
  database_url="postgresql://${app_role}:${app_password}@127.0.0.1:${pg_port}/${database_name}"
}

start_application_process() {
  # Keep a small supervisor as the process-group leader so that a silent Next.js
  # exit still leaves an actionable, secret-free diagnostic in application.log.
  # The database URL is forwarded only through the environment, never argv/logs.
  (
    cd "$frontend_dir" || {
      printf 'Launcher diagnostic: frontend working directory is unavailable.\n' >&2
      exit 125
    }
    exec setsid env \
      TRAINERCRM_PILOT_INSTANCE="$instance_marker" \
      TRAINERCRM_DATABASE_URL="$database_url" \
      NODE_ENV=development \
      bash -c '
        set +e
        printf "Launcher diagnostic: starting Next.js in %s on 127.0.0.1:%s.\n" "$1" "$3"
        "$2" dev --hostname 127.0.0.1 --port "$3" &
        child_pid=$!
        wait "$child_pid"
        child_status=$?
        printf "Launcher diagnostic: Next.js exited with status %s.\n" "$child_status" >&2
        exit "$child_status"
      ' trainercrm-app "$frontend_dir" "$frontend_dir/node_modules/.bin/next" "$app_port"
  ) </dev/null >>"$app_log" 2>&1 &
  app_pid=$!
}

record_app_identity() {
  local attempt app_start_candidate
  for attempt in $(seq 1 20); do
    app_start_candidate="$(awk '{print $22}' "/proc/$app_pid/stat" 2>/dev/null || true)"
    if [ -n "$app_start_candidate" ]; then
      printf '%s\n' "$app_pid" >"$app_pid_file"
      printf '%s\n' "$app_start_candidate" >"$app_start_file"
      return 0
    fi
    kill -0 "$app_pid" 2>/dev/null || break
    sleep 0.05
  done
  wait "$app_pid" 2>/dev/null || true
  printf 'Launcher diagnostic: application process exited before its identity could be recorded.\n' >>"$app_log"
  return 1
}

wait_for_application_readiness() {
  local deadline="$1" health_url="$2" remaining http_status
  readiness_failure=timeout
  while :; do
    if ! read_app_identity; then
      readiness_failure=exit
      return 1
    fi
    remaining=$((deadline - SECONDS))
    [ "$remaining" -gt 0 ] || return 1
    http_status="$(curl --silent --show-error --output /dev/null --write-out '%{http_code}' \
      --connect-timeout 1 --max-time "$((remaining < 2 ? remaining : 2))" "$health_url" 2>/dev/null || true)"
    [ "$http_status" = 200 ] && return 0
    read_app_identity || { readiness_failure=exit; return 1; }
    sleep 0.25
  done
}

start_postgres_raw() {
  mkdir -p "$socket_dir"; chmod 700 "$socket_dir"
  if ! "$pg_ctl" -D "$pgdata" -l "$postgres_log" -o "-c listen_addresses=127.0.0.1 -c unix_socket_directories=$socket_dir -c unix_socket_permissions=0700 -c port=$pg_port" -w start >/dev/null; then
    if [ "$initialization_in_progress" = yes ] && postgres_running; then record_initialization_server; fi
    return 1
  fi
  if [ "$initialization_in_progress" = yes ]; then record_initialization_server; fi
}

record_initialization_server() {
  initialization_postgres_pid="$(sed -n '1p' "$pgdata/postmaster.pid" 2>/dev/null)"
  [[ "$initialization_postgres_pid" =~ ^[1-9][0-9]*$ ]] || fail "Could not record initialized PostgreSQL process identity."
  initialization_postgres_start="$(awk '{print $22}' "/proc/$initialization_postgres_pid/stat" 2>/dev/null || true)"
  [ -n "$initialization_postgres_start" ] || fail "Could not record initialized PostgreSQL process start time."
  initialization_server_started=yes
}

start_command() {
  if [ ! -e "$initialized_file" ] &&
     { [ -e "$config_file" ] || [ -e "$pgdata" ] || [ -e "$credentials_file" ]; }; then
    fail "Partial initialization found. Data was retained; do not resume it in place. Run '$0 reset' only if this demo can be discarded."
  fi
  [ -d "$frontend_dir/node_modules" ] || fail "Frontend dependencies are missing; this script never installs them."
  [ -x "$frontend_dir/node_modules/.bin/next" ] || fail "Next.js executable is missing or not executable: $frontend_dir/node_modules/.bin/next"
  [ ! -e "$frontend_dir/.next/dev/lock" ] || fail "Next.js build lock is occupied; the other demo was not interrupted."
  if [ -e "$initialized_file" ]; then
    load_config
    if read_app_identity; then fail "This demo application is already running at http://127.0.0.1:$app_port"; fi
    [ -z "$(app_group_members || true)" ] || fail "Verified application process-group children are still running; use '$0 stop'."
    choose_available_ports
  else
    initialize
  fi
  if ! postgres_running; then start_postgres_raw || fail "PostgreSQL failed to start; see $postgres_log"; fi
  rm -f -- "$app_pid_file" "$app_start_file"
  build_database_url
  startup_deadline=$((SECONDS + 180))
  start_application_process
  if ! record_app_identity; then
    rm -f -- "$app_pid_file" "$app_start_file"
    fail "Application exited during process creation; see $app_log. PostgreSQL and data were retained."
  fi
  health_url="http://127.0.0.1:$app_port/api/health"
  if ! wait_for_application_readiness "$startup_deadline" "$health_url"; then
    app_process_state="$(awk '{print $3}' "/proc/$app_pid/stat" 2>/dev/null || true)"
    if [ "$readiness_failure" = timeout ] && kill -0 "$app_pid" 2>/dev/null && [ "$app_process_state" != Z ]; then
      printf 'Launcher diagnostic: readiness timed out after 180 seconds for http://127.0.0.1:%s/api/health; HTTP 200 was required.\n' "$app_port" >>"$app_log"
    else
      wait "$app_pid" 2>/dev/null || true
      printf 'Launcher diagnostic: application exited before readiness.\n' >>"$app_log"
    fi
    load_app_group_id || true
    stop_app_group || fail "Application failed readiness and verified group members survived; process records were retained."
    rm -f -- "$app_pid_file" "$app_start_file"
    fail "Application failed readiness; see $app_log. PostgreSQL and data were retained."
  fi
  printf 'TrainerCRM persistent demo started.\nBrowser URL: http://127.0.0.1:%s\nCredentials: %s\n' "$app_port" "$credentials_file"
}

stop_command() {
  load_config
  load_app_group_id || true
  if [ -n "$(app_group_members || true)" ]; then
    stop_app_group || fail "Application process-group members survived; only verified demo processes were signalled."
  elif [ -e "$app_pid_file" ] || [ -e "$app_start_file" ]; then
    printf 'Stale application record ignored; no process was signalled.\n' >&2
  fi
  rm -f -- "$app_pid_file" "$app_start_file"
  if postgres_running; then "$pg_ctl" -D "$pgdata" -m fast -w stop >/dev/null; fi
  printf 'TrainerCRM persistent demo stopped. Data retained at %s\n' "$state_dir"
}

status_command() {
  if [ ! -e "$initialized_file" ]; then
    if [ -e "$config_file" ] || [ -e "$pgdata/PG_VERSION" ]; then
      printf 'Partially initialized. Persistent data was retained at %s\n' "$state_dir"
      if [ -e "$config_file" ]; then load_config; postgres_running && printf 'PostgreSQL: running\n' || printf 'PostgreSQL: stopped\n'; fi
    else
      printf 'Not initialized. Persistent location: %s\n' "$state_dir"
    fi
    return
  fi
  load_config
  if postgres_running; then printf 'PostgreSQL: running\n'; else printf 'PostgreSQL: stopped\n'; fi
  if read_app_identity || [ -n "$(app_group_members || true)" ]; then printf 'Application: running\nBrowser URL: http://127.0.0.1:%s\n' "$app_port"; else printf 'Application: stopped\n'; fi
  printf 'Credentials: %s\nData: %s\n' "$credentials_file" "$pgdata"
}

backup_command() {
  load_config; postgres_running || fail "Start the demo before creating a logical backup."
  mkdir -p "$state_dir/backups"; chmod 700 "$state_dir/backups"
  backup_file="$(mktemp --tmpdir="$state_dir/backups" "trainercrm-$(date -u +%Y%m%dT%H%M%SZ)-XXXXXXXX.dump")"
  chmod 600 "$backup_file"
  if ! "$pg_dump" -Fc -h "$socket_dir" -p "$pg_port" -U "$operator_role" -d "$database_name" -f "$backup_file" ||
     ! "$pg_restore" --list "$backup_file" >/dev/null; then
    rm -f -- "$backup_file"; fail "Backup creation or verification failed; no backup was retained."
  fi
  sha256sum "$backup_file" >"$backup_file.sha256" || { rm -f -- "$backup_file" "$backup_file.sha256"; fail "Backup checksum failed; no backup was retained."; }
  chmod 600 "$backup_file.sha256"
  printf 'Verified backup created: %s\nSHA-256: %s\n' "$backup_file" "$backup_file.sha256"
}

preserve_old_command() {
  local old_runtime old_socket old_port old_database archive launcher_pid launcher_start current_start
  old_database="$1"
  [[ "$old_database" =~ ^trainercrm_demo_[a-f0-9]{16}$ ]] || fail "Old database name must match trainercrm_demo_<16 lowercase hex characters>."
  old_runtime="${XDG_RUNTIME_DIR:-/tmp}/trainercrm-local-demo-$(id -u)"
  old_socket="$old_runtime/socket"
  [ -d "$old_runtime" ] && [ ! -L "$old_runtime" ] && [ "$(stat -c %u "$old_runtime")" = "$(id -u)" ] || fail "Old demo runtime is missing or unsafe: $old_runtime"
  [ -d "$old_socket" ] && [ ! -L "$old_socket" ] && [ "$(stat -c %u "$old_socket")" = "$(id -u)" ] || fail "Old demo private socket directory is missing or unsafe."
  [ -r "$old_runtime/launcher.pid" ] && [ -r "$old_runtime/launcher.starttime" ] || fail "Old demo launcher identity files are unavailable."
  launcher_pid="$(<"$old_runtime/launcher.pid")"; launcher_start="$(<"$old_runtime/launcher.starttime")"
  [[ "$launcher_pid" =~ ^[1-9][0-9]*$ ]] || fail "Old demo launcher identity is invalid."
  current_start="$(awk '{print $22}' "/proc/$launcher_pid/stat" 2>/dev/null || true)"
  [ -n "$current_start" ] && [ "$current_start" = "$launcher_start" ] || fail "Old demo launcher is not the recorded live process."
  old_port="$(sed -n '4p' "$old_runtime/pgdata/postmaster.pid" 2>/dev/null)"
  [[ "$old_port" =~ ^[0-9]+$ ]] || fail "Cannot safely obtain the old demo PostgreSQL port."
  mkdir -p "$state_dir/old-demo-archives"; chmod 700 "$state_dir/old-demo-archives"
  archive="$(mktemp --tmpdir="$state_dir/old-demo-archives" "old-demo-$(date -u +%Y%m%dT%H%M%SZ)-XXXXXXXX.dump")"
  chmod 600 "$archive"
  if ! "$pg_dump" -Fc -h "$old_socket" -p "$old_port" -U trainercrm_demo_operator -d "$old_database" -f "$archive" ||
     ! "$pg_restore" --list "$archive" >/dev/null; then
    rm -f -- "$archive"; fail "Old demo backup or verification failed; no archive was retained."
  fi
  sha256sum "$archive" >"$archive.sha256" || { rm -f -- "$archive" "$archive.sha256"; fail "Archive checksum failed; no archive was retained."; }
  chmod 600 "$archive.sha256"
  printf 'Verified read-only source archive created: %s\nSHA-256: %s\nNo data was imported.\n' "$archive" "$archive.sha256"
}

reset_command() {
  if [ -e "$config_file" ]; then load_config; postgres_running && fail "Stop this demo before reset."; fi
  if [ -s "$pgdata/postmaster.pid" ] && "$pg_ctl" -D "$pgdata" status >/dev/null 2>&1; then fail "A partial cluster is running; use '$0 stop' before reset."; fi
  read_app_identity && fail "Stop this demo before reset."
  printf 'Type DELETE TRAINERCRM PILOT DATA to remove %s: ' "$state_dir"
  IFS= read -r confirmation
  [ "$confirmation" = 'DELETE TRAINERCRM PILOT DATA' ] || fail "Confirmation did not match; nothing deleted."
  [ -d "$state_dir" ] && [ ! -L "$state_dir" ] || fail "Unsafe or missing state directory"
  [ "$(stat -c %u "$state_dir")" = "$(id -u)" ] || fail "State directory is not owned by the current user"
  rm -rf -- "$state_dir"
  printf 'Persistent demo data deleted.\n'
}

