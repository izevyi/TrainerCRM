cleanup_initialization() {
  local status=$?
  trap - EXIT
  if [ "$status" -ne 0 ] && [ "$initialization_in_progress" = yes ]; then
    printf 'ERROR: Initialization failed and was not marked successful. Partial data was retained at %s; do not rerun migrations in place.\n' "$pgdata" >&2
  fi
  if [ "$initialization_in_progress" = yes ] && [ "$initialization_server_started" = yes ]; then
    current_postgres_start="$(awk '{print $22}' "/proc/$initialization_postgres_pid/stat" 2>/dev/null || true)"
    if [ -n "$current_postgres_start" ] && [ "$current_postgres_start" = "$initialization_postgres_start" ] && postgres_running; then
      "$pg_ctl" -D "$pgdata" -m fast -w stop >/dev/null 2>&1 || printf 'ERROR: Failed initialization left its PostgreSQL process running; data retained at %s\n' "$pgdata" >&2
    fi
  fi
  umask "$old_umask"
  exit "$status"
}
